"""Audio library: audio_library/music and audio_library/sfx next to the app."""
import os, random, subprocess

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LIB = os.environ.get("CLIPFORGE_AUDIO_DIR") or os.path.join(ROOT, "audio_library")
EXT = (".mp3", ".wav", ".m4a", ".aac", ".ogg", ".flac")


def folder(kind):
    p = os.path.join(LIB, kind)
    os.makedirs(p, exist_ok=True)
    return p


def list_files(kind):
    return sorted(f for f in os.listdir(folder(kind)) if f.lower().endswith(EXT))


def resolve(kind, name):
    """name = a file name inside the library folder, or 'random' (music only). Paths are refused, so nobody can
    point FFmpeg at other files on the computer."""
    if not name or name in ("(none)", "none") or name != os.path.basename(name) or name.startswith("."):
        return None
    if name == "random" and kind == "music":
        files = list_files("music")
        return os.path.join(folder("music"), random.choice(files)) if files else None
    p = os.path.join(folder(kind), name)
    return p if os.path.isfile(p) else None


# Starter effects generated by FFmpeg itself (no copyright issues). Add your own files to the folder too.
_STARTER = {
    "whoosh.wav": ["-f", "lavfi", "-i", "anoisesrc=d=0.7:c=pink:a=0.6", "-af",
                   "highpass=f=250,lowpass=f=5000,afade=t=in:d=0.3,afade=t=out:st=0.35:d=0.35"],
    "hit.wav": ["-f", "lavfi", "-i", "aevalsrc=sin(2*PI*55*t)*exp(-6*t)+0.4*sin(2*PI*110*t)*exp(-9*t):d=0.6:s=44100"],
    "ding.wav": ["-f", "lavfi", "-i", "aevalsrc=0.6*sin(2*PI*1320*t)*exp(-5*t):d=0.9:s=44100"],
    "pop.wav": ["-f", "lavfi", "-i", "aevalsrc=0.8*sin(2*PI*600*t)*exp(-30*t):d=0.25:s=44100"],
}


def make_starter_sfx(ffmpeg):
    made = []
    for name, args in _STARTER.items():
        out = os.path.join(folder("sfx"), name)
        if not os.path.exists(out):
            subprocess.run([ffmpeg, "-y", "-loglevel", "error"] + args + [out], check=True)
            made.append(name)
    return made
